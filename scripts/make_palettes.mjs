// Writes the palette CSS variables (from src/palettes.js) into styles.css
// between the PALETTES markers: node scripts/make_palettes.mjs
import fs from 'fs';
import { PALETTES } from '../src/palettes.js';

const file = new URL('../styles.css', import.meta.url);
const css = fs.readFileSync(file, 'utf8');
const start = '/* PALETTES:begin (generated by scripts/make_palettes.mjs) */';
const end = '/* PALETTES:end */';
const blocks = PALETTES.map((p) => {
  const d = p.stops.dark, l = p.stops.light;
  return `:root[data-palette="${p.id}"] {
  --accent: ${p.css.accent}; --accent-rgb: ${p.css.rgb}; --accent-2: ${d[1]};
  --accent-grad: ${p.css.grad};
  --accent-glow: 0 8px 28px rgba(${p.css.rgb}, .4); --on-accent: ${p.css.on};
  --bg-glow: rgba(${p.css.rgb}, .14); --gauge-glow: ${d[3]}80; --lb-top: ${d[1]};
}
:root[data-theme="light"][data-palette="${p.id}"] {
  --accent: ${p.css.lightAccent}; --bg-glow: rgba(${p.css.rgb}, .10); --gauge-glow: ${l[3]}4d; --lb-top: ${p.css.lightAccent};
}`;
}).join('\n');
const out = `${start}\n${blocks}\n${end}`;
const i = css.indexOf(start), j = css.indexOf(end);
if (i < 0 || j < 0) throw new Error('PALETTES markers not found in styles.css');
fs.writeFileSync(file, css.slice(0, i) + out + css.slice(j + end.length));
console.log(`${PALETTES.length} palettes written`);
